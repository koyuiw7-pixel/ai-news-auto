def _broad_outline(middle: str, use_title: str = "使える・申し込めるか", relate: str = RELATE_GENERIC) -> str:
    """幅広い話題の共通章立て（概要 → 中身 → 自分に関係ある？ → 使える？ → まとめ）"""
    return f"""## 概要
短い文3〜4つで、この発表を専門用語なしで説明する。「何が決まった/始まったのか」「誰に影響があるのか」を、
専門外の社会人にも伝わる大人の言葉で書く。1段落は1〜3文。ここだけ読めば全体がつかめるようにする。

## 何が発表された？
リード文の続きとして、300〜400字で「誰が・何を・いつ・どこまで」を元記事の事実だけで整理する。
発表の位置づけ（新しい取り組みか、既存の変更か、予定か開始済みか）を明確にする。

{middle}

## 自分に関係ある？
{relate}

## {use_title}
読者が実際に使う・買う・申し込む・参加する方法（窓口、期間、価格、条件）を箇条書きで。
元記事に無い項目は書かない。方法がまだ発表されていなければ、そう1文で書き、公式情報の確認先（発信元の名前）を示す。
使う・申し込む性質の話題でない場合は、読者が次にできること（公式発表の確認、関連制度のチェック等）を書く。

## まとめ
今後の予定と、読者が次に取るべき行動を短い文で2〜3つ。"""


